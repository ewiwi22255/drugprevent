"""
安全護欄：危機偵測 + 求助資源。

設計原則（重要）：
安全邊界在「程式」，不在 system prompt。對於跟青少年談毒品 / 心理的 AI，
偵測到危機訊號時，必須由程式「強制」附上正確的求助專線，不能只依賴 LLM 自願。

限制（誠實說明）：
關鍵字偵測是啟發式安全網，會有漏判與誤判，不取代專業危機服務。
它的目的只是確保「高風險訊息一定看得到真人求助管道」，並建議轉介真人。

專線經官方來源核實（issue #14）：
- 1925 安心專線（衛福部，24h 免費心理支持）
- 1995 生命線、1980 張老師專線
- 0800-770-885 毒品危害防制諮詢（法務部 / 各地毒防中心，24h 免付費）
- 110 報警 / 119 救護（生命危急）
"""
import re

# ── 危機關鍵字（高風險：輕生 / 自傷 / 急性過量 / 立即危險）────────────────
_CRISIS_KEYWORDS = [
    # 輕生 / 自傷
    "自殺", "想死", "不想活", "活不下去", "輕生", "結束生命", "結束自己",
    "了結自己", "傷害自己", "自殘", "割腕", "跳樓", "燒炭", "上吊",
    # 急性中毒 / 過量（醫療緊急）
    "吞了一堆", "吃了一堆", "服用過量", "用過量", "吸過量", "藥物過量",
    "中毒", "昏迷", "叫不醒", "沒有呼吸", "沒呼吸", "抽搐", "暈倒", "失去意識",
    # 立即危險 / 受暴
    "救命", "被打", "被虐待", "被性侵", "有人要傷害",
]
_CRISIS_RE = re.compile("|".join(re.escape(k) for k in _CRISIS_KEYWORDS))


def assess_risk(text: str) -> str:
    """評估訊息風險。回傳 'crisis' 或 'none'。

    啟發式：寧可誤報也不漏報高風險（誤報的代價只是多看到一次專線）。
    """
    if not text:
        return "none"
    return "crisis" if _CRISIS_RE.search(text) else "none"


